/* Refresh the offline footer baseline from the iDrive release's own metadata. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),source=path.resolve(process.argv[2]||path.join(root,'../BimmerVision/recorder/files/version.json'));
const info=JSON.parse(fs.readFileSync(source,'utf8'));
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(info.version)||info.repository!=='Hexphase/BimmerVision')throw Error('Invalid iDrive version metadata');
const data=JSON.stringify({version:info.version,repository:info.repository});
fs.writeFileSync(path.join(root,'app-version-data.js'),'/* Generated by npm run sync:idrive-version. */\n(function(root){const info='+data+';if(typeof module!=="undefined"&&module.exports)module.exports=info;else root.BV_IDRIVE_VERSION=info;})(globalThis);\n');
const pkgPath=path.join(root,'package.json'),pkg=JSON.parse(fs.readFileSync(pkgPath,'utf8'));
pkg.version=info.version;fs.writeFileSync(pkgPath,JSON.stringify(pkg,null,2)+'\n');
for(const file of ['source-manager.js','index.html']){
 const target=path.join(root,file),text=fs.readFileSync(target,'utf8');
 fs.writeFileSync(target,text.replace(file==='index.html'?/BimmerVision Web \d+\.\d+\.\d+/g:/version:'\d+\.\d+\.\d+'|BV_WEB_VERSION='\d+\.\d+\.\d+'/g,match=>match.replace(/\d+\.\d+\.\d+/,info.version)));
}
process.stdout.write('Web and offline iDrive version: '+info.version+'\n');
